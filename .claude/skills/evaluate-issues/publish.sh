#!/usr/bin/env bash
# Publish one verdict to an ngit issue: its comment, then the label its heading
# names (verdict-format.md). A re-check note gets no label, and a failed comment
# stops before the label. Run from a checkout of the repo, on the person's OK:
#   bash <this skill's folder>/publish.sh <issue id or nevent> <comment file>
# A script rather than an inline --body "$(cat …)": a worktree-isolated Claude
# Code session refuses command substitution in a command that names git, and
# reads ngit as git.
set -euo pipefail
[ $# -eq 2 ] || { echo "usage: publish.sh <issue id or nevent> <comment file>" >&2; exit 2; }
id=$1 file=$2
[ -s "$file" ] || { echo "publish.sh: $file is missing or empty" >&2; exit 2; }
case "$(sed -n 1p "$file")" in
  '> **Issue Evaluator** · generated by AI · rubric v'*) ;;
  *) echo "publish.sh: $file doesn't start with the marker line" >&2; exit 2 ;;
esac
ready=$(grep -cx '## Ready to one shot' "$file" || true)
not_ready=$(grep -cx '## Not ready to one shot' "$file" || true)
case "$ready $not_ready" in
  '1 0') label=ready-to-one-shot ;;
  '0 1') label=not-ready-to-one-shot ;;
  *) echo "publish.sh: $file needs exactly one verdict heading" >&2; exit 2 ;;
esac
if grep -q '^Re-checked after ' "$file"; then label=; fi
ngit issue comment "$id" --body "$(cat "$file")" --defaults --repo-relay-only
if [ -n "$label" ]; then
  ngit issue label "$id" --label "$label" --defaults --repo-relay-only
fi
echo "publish.sh: posted the comment${label:+ and the $label label} on $id"
