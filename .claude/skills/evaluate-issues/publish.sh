#!/usr/bin/env bash
# Publish one verdict to an ngit issue: its comment, then the label its heading
# names (verdict-format.md). With --recheck it posts a re-check note and no label.
# First it re-reads the issue, and posts nothing if a comment, an edit, a label or
# another verdict arrived after the bundle was gathered: the judge never saw it,
# and a label that appears while judging may be one an issue talked a judge into.
# Run from a checkout of the repo, on the person's OK:
#   bash <this skill's folder>/publish.sh [--recheck] <bundle.json> <comment file>
# Exit: 0 posted · 1 ngit failed · 2 bad input, nothing posted ·
#       3 the issue changed after gathering, nothing posted.
# A script rather than an inline --body "$(cat …)": a worktree-isolated Claude
# Code session refuses command substitution in a command that names git, and
# reads ngit as git.
set -euo pipefail
die() { echo "publish.sh: $*" >&2; exit 2; }
recheck=
if [ "${1:-}" = --recheck ]; then recheck=1; shift; fi
[ $# -eq 2 ] || die "usage: publish.sh [--recheck] <bundle.json> <comment file>"
bundle=$1 file=$2

[ -s "$bundle" ] || die "$bundle is missing or empty"
nevent=$(jq -r '.nevent // empty' "$bundle" 2>/dev/null) || die "$bundle isn't JSON"
[ -n "$nevent" ] || die "$bundle has no nevent"
[ -s "$file" ] || die "$file is missing or empty"
case "$(sed -n 1p "$file")" in
  '> **Issue Evaluator** · generated by AI · rubric v'*) ;;
  *) die "$file doesn't start with the marker line" ;;
esac
ready=$(grep -cx '## Ready to one shot' "$file" || true)
not_ready=$(grep -cx '## Not ready to one shot' "$file" || true)
case "$ready $not_ready" in
  '1 0') label=ready-to-one-shot section='^\*\*Done when\*\*' ;;
  '0 1') label=not-ready-to-one-shot section='^\*\*What would make it ready:\*\*$' ;;
  *) die "$file needs exactly one verdict heading" ;;
esac
first=$(awk 'h && NF { print; exit } /^## (Not ready|Ready) to one shot$/ { h = 1 }' "$file")
if [ -n "$recheck" ]; then
  case "$first" in
    'Re-checked after '*) ;;
    *) die "$file isn't a re-check note: its first line under the heading must start \"Re-checked after \"" ;;
  esac
  if grep -Eq '^\*\*(Done when|What would make it ready:)' "$file"; then die "$file is a full verdict; drop --recheck"; fi
  label=
elif ! grep -Eq "$section" "$file"; then
  die "$file isn't a full verdict for its heading; a re-check note needs --recheck"
fi

view=$(mktemp "${TMPDIR:-/tmp}/publish-view.XXXXXX")
trap 'rm -f "$view"' EXIT
if ! ngit issue view "$nevent" --comments --history --json > "$view"; then
  echo "publish.sh: couldn't re-read $nevent; nothing posted" >&2; exit 1
fi
new=$(jq -r --slurpfile b "$bundle" '
  [$b[0].issue.comments[]?.id, $b[0].issue.edit_history[]?.id] as $seen
  | ($b[0].issue.labels // []) as $had
  | (.comments[]? | select(.id as $i | $seen | index($i) | not)
       | "comment by \(.author[0:16])… at \(.created_at): \((.body // "") | split("\n")[0])"),
    (.edit_history[]? | select(.id as $i | $seen | index($i) | not)
       | "edit by \(.author[0:16])… at \(.created_at)"),
    (((.labels // []) - $had)[] | "label \(.) added")' "$view") \
  || { echo "publish.sh: couldn't parse the re-read of $nevent; nothing posted" >&2; exit 1; }
if [ -n "$new" ]; then
  echo "publish.sh: $nevent changed after its bundle was gathered. The judge never saw:" >&2
  sed 's/^/  /' <<< "$new" >&2
  echo "Nothing posted. Gather it again and re-judge it, or ask." >&2
  exit 3
fi

if ! ngit issue comment "$nevent" --body "$(cat "$file")" --defaults --repo-relay-only; then
  echo "publish.sh: the comment failed, so no label was posted" >&2; exit 1
fi
if [ -n "$label" ] && ! ngit issue label "$nevent" --label "$label" --defaults --repo-relay-only; then
  echo "publish.sh: the comment is up but the $label label failed. Don't run publish.sh again; the next run offers the label alone." >&2
  exit 1
fi
echo "publish.sh: posted the comment${label:+ and the $label label} on $nevent"
